import { chromium } from "playwright";
const exe = "C:/Users/ydx15/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe";
const browser = await chromium.launch({ executablePath: exe, headless: true });
const page = await (await browser.newContext()).newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(String(e).slice(0, 120)));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 100)); });
await page.goto("http://127.0.0.1:4173/#/invite");
await page.waitForTimeout(2000);
console.log("invite URL:", page.url().slice(0, 50));
console.log("demo-tips:", await page.locator(".demo-tips button").count());
console.log("页面文本:", (await page.locator("body").innerText()).slice(0, 150).replace(/\n/g, " "));
await page.locator(".demo-tips button").first().click();
await page.waitForTimeout(400);
await page.locator("button:has-text('加入平台')").click();
await page.waitForTimeout(2000);
console.log("加入后 URL:", page.url().slice(0, 60));
console.log("错误:", errs.slice(0, 4));
await browser.close();
